import type { FC } from 'react';
import { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { Check, Flame, History, Plus, Share2, Trash2 } from 'lucide-react';
import { api } from '../api/client';
import type { Roast } from '../api/types';

interface HistoryPageProps {
  onNavigate: (route: string) => void;
}

export const HistoryPage: FC<HistoryPageProps> = ({ onNavigate }) => {
  const [copiedId, setCopiedId] = useState<string | null>(null);

  const { data: roasts, isLoading, refetch } = useQuery<Roast[]>({
    queryKey: ['roasts'],
    queryFn: () => api.listRoasts(),
  });

  const handleDelete = async (id: string) => {
    if (!confirm('Are you sure you want to delete this roast from your history?')) return;
    try {
      await api.deleteRoast(id);
      refetch();
    } catch (err: any) {
      alert('Failed to delete roast: ' + err.message);
    }
  };

  const handleShare = async (roast: Roast) => {
    try {
      const res = await api.shareRoast(roast.id);
      const url = window.location.origin + res.shareUrl;
      await navigator.clipboard.writeText(url);
      setCopiedId(roast.id);
      setTimeout(() => setCopiedId(null), 2500);
    } catch (err: any) {
      alert('Failed to share: ' + err.message);
    }
  };

  if (isLoading) {
    return (
      <div className="min-h-[60vh] flex flex-col items-center justify-center text-center">
        <div className="w-10 h-10 border-2 border-orange-500 border-t-transparent rounded-full animate-spin mb-4" />
        <p className="text-sm text-slate-400">Loading your roast archive...</p>
      </div>
    );
  }

  return (
    <div className="max-w-5xl mx-auto px-4 py-8">
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-4 mb-8">
        <div>
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-orange-500/10 border border-orange-500/30 text-orange-400 text-xs font-semibold mb-2">
            <History className="w-3.5 h-3.5" />
            <span>Roast Archive</span>
          </div>
          <h1 className="text-3xl font-black font-['Outfit']">Your Hall of Shame</h1>
          <p className="text-slate-400 text-sm">Past verdicts generated by our merciless LLM.</p>
        </div>

        <button
          onClick={() => onNavigate('/roast')}
          className="py-2.5 px-5 rounded-xl bg-orange-600 hover:bg-orange-500 text-white font-bold text-xs flex items-center gap-2 shadow-lg shadow-orange-500/20 transition-all hover:scale-[1.02]"
        >
          <Plus className="w-4 h-4" />
          <span>New Roast</span>
        </button>
      </div>

      {/* Roasts Grid */}
      {roasts && roasts.length > 0 ? (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          {roasts.map((roast) => (
            <div
              key={roast.id}
              className="glass-panel p-6 rounded-2xl border border-slate-800 flex flex-col justify-between hover:border-slate-700 transition-all group"
            >
              <div>
                <div className="flex items-center justify-between mb-4">
                  <span className="px-2.5 py-0.5 rounded-full bg-orange-500/20 text-orange-400 border border-orange-500/30 text-[10px] font-bold">
                    🔥 {roast.tone}
                  </span>
                  <span className="text-[11px] text-slate-500">
                    {new Date(roast.createdAt).toLocaleDateString(undefined, {
                      month: 'short',
                      day: 'numeric',
                      year: 'numeric',
                    })}
                  </span>
                </div>

                <p className="text-sm font-serif italic text-slate-200 leading-relaxed mb-6 line-clamp-4">
                  “{roast.roastText || 'Processing roast...'}”
                </p>
              </div>

              <div className="pt-4 border-t border-slate-800/80 flex items-center justify-between text-xs text-slate-400">
                <span className="text-[11px] text-slate-500 truncate max-w-[150px]">
                  {roast.sources.replace(',', ' • ')}
                </span>

                <div className="flex items-center gap-2">
                  <button
                    onClick={() => handleShare(roast)}
                    className="p-2 rounded-lg bg-slate-900 hover:bg-slate-800 text-slate-300 hover:text-white transition-colors"
                    title="Share roast card"
                  >
                    {copiedId === roast.id ? (
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                    ) : (
                      <Share2 className="w-3.5 h-3.5" />
                    )}
                  </button>

                  <button
                    onClick={() => handleDelete(roast.id)}
                    className="p-2 rounded-lg bg-slate-900 hover:bg-rose-500/10 text-slate-400 hover:text-rose-400 transition-colors"
                    title="Delete roast"
                  >
                    <Trash2 className="w-3.5 h-3.5" />
                  </button>
                </div>
              </div>
            </div>
          ))}
        </div>
      ) : (
        <div className="glass-panel p-12 rounded-2xl border border-slate-800 text-center max-w-md mx-auto my-12">
          <Flame className="w-12 h-12 text-slate-600 mx-auto mb-4" />
          <h3 className="text-lg font-bold text-white mb-2">No Roasts Yet</h3>
          <p className="text-sm text-slate-400 mb-6">
            You haven't subjected yourself to our roast engine yet. What are you waiting for?
          </p>
          <button
            onClick={() => onNavigate('/roast')}
            className="px-6 py-2.5 rounded-xl bg-orange-600 hover:bg-orange-500 text-white text-xs font-bold transition-all"
          >
            Generate First Roast
          </button>
        </div>
      )}
    </div>
  );
};
